/** Icon for a browse-listing thumbnail kind. */
export function ThumbGlyph({ kind = 'box', size = 20 }) {
  switch (kind) {
    case 'bike':
      return <BikeIcon size={size} />
    case 'laptop':
      return <LaptopIcon size={size} />
    case 'sneaker':
      return <FootprintsIcon size={size} />
    case 'tag':
      return <TagIcon size={size} />
    default:
      return <BoxIcon size={size} />
  }
}

/** Icon for a session kind (drawer rows + session view header). */
